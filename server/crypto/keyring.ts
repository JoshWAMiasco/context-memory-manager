import "server-only";
import { randomUUID } from "node:crypto";
import { getEventBus } from "@/server/events/bus";
import { getGlobalSingleton } from "@/server/runtime/global-singleton";

/*
 * Every encryption key CCM holds lives here, in memory only: folders a session unlocked,
 * keys waiting in the Enable encryption wizard, and keys a running job uses. Keys are wiped
 * (`fill(0)`) when they expire, when the session locks or ends, and when the process exits. They
 * are never logged, serialized or sent to a client.
 */

export const PENDING_KEY_MILLISECONDS = 15 * 60 * 1000;

interface UnlockedFolder {
  storageId: string;
  /** The folder's path when it was unlocked (it may be renamed since). */
  scopePath: string;
  /** DEKs by base64 key id: one, or two while the folder is re-keyed. */
  keys: Map<string, Buffer>;
  expiresAt: number;
  timer: NodeJS.Timeout;
}

/** A key generated by `prepare`, waiting for the user to download and verify its key file. */
export interface PendingKey {
  pendingId: string;
  kind: "encrypt" | "rekey";
  storageId: string;
  scopePath: string;
  folderId: string;
  folderName: string;
  dek: Buffer;
  keyId: Buffer;
  createdAt: string;
  isVerified: boolean;
  expiresAt: number;
  /** Re-key only: the folder's current key, from the old key file. */
  oldKey?: { dek: Buffer; keyId: Buffer };
}

interface KeyringState {
  sessions: Map<string, Map<string, UnlockedFolder>>;
  pending: Map<string, Map<string, PendingKey>>;
  jobs: Map<string, Map<string, Buffer>>;
  isSubscribed: boolean;
}

function wipeKeys(keys: Iterable<Buffer>): void {
  for (const key of keys) key.fill(0);
}

function wipePending(pendingKey: PendingKey): void {
  pendingKey.dek.fill(0);
  pendingKey.oldKey?.dek.fill(0);
}

function getState(): KeyringState {
  const state = getGlobalSingleton<KeyringState>("crypto-keyring", () => ({
    sessions: new Map(),
    pending: new Map(),
    jobs: new Map(),
    isSubscribed: false,
  }));
  if (!state.isSubscribed) {
    state.isSubscribed = true;
    const eventBus = getEventBus();
    eventBus.on("session.locked", ({ sessionIdHash }) => lockAll(sessionIdHash, "session"));
    eventBus.on("session.destroyed", ({ sessionIdHash }) => lockAll(sessionIdHash, "session"));
    process.once("exit", wipeEverything);
  }
  return state;
}

function emitChange(
  sessionIdHash: string,
  folder: Pick<UnlockedFolder, "storageId" | "scopePath">,
  folderId: string,
  change: "unlocked" | "locked",
): void {
  getEventBus().emit("encryption.changed", {
    sessionIdHash,
    storageId: folder.storageId,
    path: folder.scopePath,
    folderId,
    change,
  });
}

/**
 * Holds a folder's key for a session until `expiresAt` (the unlock time, never past the session).
 * Unlocking again replaces the old entry; extra keys (re-keying) are added to it.
 *
 * @example
 * unlockFolder(sessionIdHash, { folderId, storageId, scopePath: "persona", keys: [{ keyId, dek }], expiresAt });
 */
export function unlockFolder(
  sessionIdHash: string,
  {
    folderId,
    storageId,
    scopePath,
    keys,
    expiresAt,
  }: {
    folderId: string;
    storageId: string;
    scopePath: string;
    keys: readonly { keyId: Buffer; dek: Buffer }[];
    expiresAt: number;
  },
): void {
  const { sessions } = getState();
  const sessionFolders = sessions.get(sessionIdHash) ?? new Map<string, UnlockedFolder>();
  sessions.set(sessionIdHash, sessionFolders);
  const existing = sessionFolders.get(folderId);
  if (existing) clearTimeout(existing.timer);
  const keyMap = existing?.keys ?? new Map<string, Buffer>();
  for (const { keyId, dek } of keys) {
    keyMap.get(keyId.toString("base64"))?.fill(0);
    keyMap.set(keyId.toString("base64"), Buffer.from(dek));
  }
  const timer = setTimeout(
    () => lockFolder(sessionIdHash, folderId),
    Math.max(0, Math.min(expiresAt - Date.now(), 2 ** 31 - 1)),
  );
  timer.unref();
  sessionFolders.set(folderId, { storageId, scopePath, keys: keyMap, expiresAt, timer });
  emitChange(sessionIdHash, { storageId, scopePath }, folderId, "unlocked");
}

/** The folder's DEK for `keyId` in this session, or undefined when it is locked (or expired). */
export function readFolderKey(sessionIdHash: string | undefined, folderId: string, keyId: string): Buffer | undefined {
  if (!sessionIdHash) return undefined;
  const unlockedFolder = getState().sessions.get(sessionIdHash)?.get(folderId);
  if (!unlockedFolder) return undefined;
  if (unlockedFolder.expiresAt <= Date.now()) {
    lockFolder(sessionIdHash, folderId);
    return undefined;
  }
  return unlockedFolder.keys.get(keyId);
}

/** When the folder locks again for this session, or undefined when it is locked. */
export function readUnlockExpiry(sessionIdHash: string | undefined, folderId: string): number | undefined {
  if (!sessionIdHash) return undefined;
  const unlockedFolder = getState().sessions.get(sessionIdHash)?.get(folderId);
  if (!unlockedFolder || unlockedFolder.expiresAt <= Date.now()) return undefined;
  return unlockedFolder.expiresAt;
}

/** The folders this session has unlocked, by folder id. */
export function listUnlockedFolders(
  sessionIdHash: string | undefined,
): { folderId: string; storageId: string; scopePath: string; expiresAt: number }[] {
  if (!sessionIdHash) return [];
  const now = Date.now();
  return [...(getState().sessions.get(sessionIdHash) ?? new Map<string, UnlockedFolder>())]
    .filter(([, unlockedFolder]) => unlockedFolder.expiresAt > now)
    .map(([folderId, unlockedFolder]) => ({
      folderId,
      storageId: unlockedFolder.storageId,
      scopePath: unlockedFolder.scopePath,
      expiresAt: unlockedFolder.expiresAt,
    }));
}

/** Wipes one folder's key for one session. */
export function lockFolder(sessionIdHash: string, folderId: string): void {
  const sessionFolders = getState().sessions.get(sessionIdHash);
  const unlockedFolder = sessionFolders?.get(folderId);
  if (!sessionFolders || !unlockedFolder) return;
  clearTimeout(unlockedFolder.timer);
  wipeKeys(unlockedFolder.keys.values());
  sessionFolders.delete(folderId);
  if (sessionFolders.size === 0) getState().sessions.delete(sessionIdHash);
  emitChange(sessionIdHash, unlockedFolder, folderId, "locked");
}

/** Wipes a folder's key in every session (after it is decrypted or re-keyed). */
export function lockFolderEverywhere(folderId: string): void {
  for (const sessionIdHash of [...getState().sessions.keys()]) lockFolder(sessionIdHash, folderId);
}

/**
 * Wipes every key a session holds: Lock all, or the session locking or ending ("session"), which
 * also drops its pending wizard keys.
 */
export function lockAll(sessionIdHash: string, reason: "user" | "session" = "user"): void {
  const state = getState();
  for (const folderId of [...(state.sessions.get(sessionIdHash)?.keys() ?? [])]) lockFolder(sessionIdHash, folderId);
  if (reason === "session") {
    for (const pendingKey of state.pending.get(sessionIdHash)?.values() ?? []) wipePending(pendingKey);
    state.pending.delete(sessionIdHash);
  }
}

/**
 * Stores a freshly generated key for the wizard; it expires after 15 minutes. The keyring keeps its
 * own copies of the keys, so the caller can (and should) wipe the buffers it passed in.
 */
export function storePendingKey(
  sessionIdHash: string,
  pendingKey: Omit<PendingKey, "pendingId" | "isVerified" | "expiresAt">,
): PendingKey {
  const { pending } = getState();
  const sessionPending = pending.get(sessionIdHash) ?? new Map<string, PendingKey>();
  pending.set(sessionIdHash, sessionPending);
  const now = Date.now();
  for (const [pendingId, existing] of sessionPending) {
    if (existing.expiresAt > now) continue;
    wipePending(existing);
    sessionPending.delete(pendingId);
  }
  const storedKey: PendingKey = {
    ...pendingKey,
    dek: Buffer.from(pendingKey.dek),
    keyId: Buffer.from(pendingKey.keyId),
    ...(pendingKey.oldKey
      ? { oldKey: { dek: Buffer.from(pendingKey.oldKey.dek), keyId: Buffer.from(pendingKey.oldKey.keyId) } }
      : {}),
    pendingId: randomUUID(),
    isVerified: false,
    expiresAt: now + PENDING_KEY_MILLISECONDS,
  };
  sessionPending.set(storedKey.pendingId, storedKey);
  return storedKey;
}

/** A pending key of this session, or undefined when it doesn't exist or expired. */
export function readPendingKey(sessionIdHash: string | undefined, pendingId: string): PendingKey | undefined {
  if (!sessionIdHash) return undefined;
  const sessionPending = getState().pending.get(sessionIdHash);
  const pendingKey = sessionPending?.get(pendingId);
  if (!pendingKey) return undefined;
  if (pendingKey.expiresAt <= Date.now()) {
    wipePending(pendingKey);
    sessionPending?.delete(pendingId);
    return undefined;
  }
  return pendingKey;
}

/** Forgets a pending key (it was used to start a job). Its buffers are wiped. */
export function discardPendingKey(sessionIdHash: string, pendingId: string): void {
  const sessionPending = getState().pending.get(sessionIdHash);
  const pendingKey = sessionPending?.get(pendingId);
  if (!pendingKey) return;
  wipePending(pendingKey);
  sessionPending?.delete(pendingId);
}

/** Gives a job its own copies of the keys it needs (wiped when the job ends or CCM stops). */
export function storeJobKeys(jobId: string, keys: readonly { keyId: Buffer; dek: Buffer }[]): void {
  const { jobs } = getState();
  wipeKeys(jobs.get(jobId)?.values() ?? []);
  jobs.set(jobId, new Map(keys.map(({ keyId, dek }) => [keyId.toString("base64"), Buffer.from(dek)])));
}

/** A job's key for `keyId`, or undefined. */
export function readJobKey(jobId: string, keyId: string): Buffer | undefined {
  return getState().jobs.get(jobId)?.get(keyId);
}

export function hasJobKeys(jobId: string): boolean {
  return getState().jobs.has(jobId);
}

export function discardJobKeys(jobId: string): void {
  const { jobs } = getState();
  wipeKeys(jobs.get(jobId)?.values() ?? []);
  jobs.delete(jobId);
}

/** How many keys are held in total; the test-only debug endpoint reports it . */
export function countHeldKeys(): { sessions: number; pending: number; jobs: number } {
  const state = getState();
  let sessionKeys = 0;
  for (const sessionFolders of state.sessions.values()) {
    for (const unlockedFolder of sessionFolders.values()) sessionKeys += unlockedFolder.keys.size;
  }
  let pendingKeys = 0;
  for (const sessionPending of state.pending.values()) pendingKeys += sessionPending.size;
  return { sessions: sessionKeys, pending: pendingKeys, jobs: state.jobs.size };
}

/** How many keys one session holds. */
export function countSessionKeys(sessionIdHash: string | undefined): number {
  if (!sessionIdHash) return 0;
  let keyCount = 0;
  for (const unlockedFolder of getState().sessions.get(sessionIdHash)?.values() ?? [])
    keyCount += unlockedFolder.keys.size;
  return keyCount;
}

/** Wipes every key (process exit, tests). */
export function wipeEverything(): void {
  const state = getState();
  for (const sessionFolders of state.sessions.values()) {
    for (const unlockedFolder of sessionFolders.values()) {
      clearTimeout(unlockedFolder.timer);
      wipeKeys(unlockedFolder.keys.values());
    }
  }
  for (const sessionPending of state.pending.values())
    for (const pendingKey of sessionPending.values()) wipePending(pendingKey);
  for (const jobKeys of state.jobs.values()) wipeKeys(jobKeys.values());
  state.sessions.clear();
  state.pending.clear();
  state.jobs.clear();
}
